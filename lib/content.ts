/** "10:30 – 16:30", or just the start when no end is confirmed. */
export function scheduleRange(row: ScheduleRow, dash = '–'): string {
  return row.end ? `${row.time} ${dash} ${row.end}` : row.time;
}

/* --- Derived event facts. One source of truth: `format` + SCHEDULE. -------- */

/** Second segment of `format` — "120 min", "bracket", "all day". */
export function eventDuration(event: AnvikshaEvent): string | null {
  const parts = event.format.split('·').map((s) => s.trim());
  return parts[1] || null;
}

/** First segment of `format` — the informal team shape shown on the card chip. */
export function eventFormatTeam(event: AnvikshaEvent): string | null {
  const parts = event.format.split('·').map((s) => s.trim());
  return parts[0] || null;
}

/** Strips the display prefix so "Sidequest — Through the Lens" matches a row. */
function scheduleNeedle(name: string) {
  return name.replace(/^sidequest\s*[—-]\s*/i, '').toLowerCase();
}

/** Schedule rows that mention this event, in run order. */
export function eventScheduleRows(event: AnvikshaEvent): ScheduleRow[] {
  const needle = scheduleNeedle(event.name);
  return SCHEDULE.filter((row) => row.slot.toLowerCase().includes(needle));
}

/** Venue from the run-of-show; null when no row mentions the event. */
export function eventVenue(event: AnvikshaEvent): string | null {
  return eventScheduleRows(event)[0]?.venue ?? null;
}

/** Start time from the run-of-show; null when no row mentions the event. */
export function eventStartTime(event: AnvikshaEvent): string | null {
  return eventScheduleRows(event)[0]?.time ?? null;
}

/* ---------------------------------------------------------------------------
   PRIZE POOL

   NEEDS DATA: `total` and every category `amount` below. While the headline
   total resolves to null the whole prize section does not render — no
   placeholder numbers ship.

   Per-event prizes live on the event objects (`prize`). `prizeFromEvents()`
   adds those up so the two can never drift: leave `total` null once every
   event carries a real prize and the section uses the computed sum instead.
   --------------------------------------------------------------------------- */
export interface PrizeCategory {
  /** Matches an Era `category`, or a custom bucket. */
  label: string;
  amount: number | null;
  note?: string;
}

export interface PrizePool {
  currency: string;
  /** Headline number. Null here falls back to the sum of per-event prizes. */
  total: number | null;
  categories: PrizeCategory[];
}

