export interface AnvikshaEvent {
  id: string;
  /** URL segment: /events/<slug>. Kept identical to `id`. */
  slug: string;
  name: string;
  tagline: string;
  blurb: string;
  scene: SceneKey;
  /** Short chip copy, e.g. "Teams of 3 · 120 min". Duration is parsed from it. */
  format: string;

  /* --- NEEDS DATA: supplied per event, null until then ------------------- */
  /** Full rule set, one string per bullet. */
  rules: string[] | null;
  /** Confirmed team size, e.g. "3–4 members". */
  teamSize: string | null;
  /** Confirmed prize for this event, in rupees. Feeds the prize pool section. */
  prize: number | null;
  /** Direct Unstop registration URL for this event. */
  unstopUrl: string | null;
}

export interface Era {
  id: EraId;
  key: string;
  label: string;
  years: string;
  category: string;
  headline: string;
  description: string;
  accent: string;
  events: AnvikshaEvent[];
}

/* Every event literal below omits the four gap fields; this fills them with
   null so the type stays honest without repeating `rules: null` 21 times. */
type EventSeed = Omit<AnvikshaEvent, 'slug' | 'rules' | 'teamSize' | 'prize' | 'unstopUrl'> &
  Partial<Pick<AnvikshaEvent, 'rules' | 'teamSize' | 'prize' | 'unstopUrl'>>;

const ev = (seed: EventSeed): AnvikshaEvent => ({
  slug: seed.id,
  rules: null,
  teamSize: null,
  prize: null,
  unstopUrl: null,
  ...seed,
});

