/** Sum of every confirmed per-event prize. Null when none are set yet. */
export function prizeFromEvents(): number | null {
  const known = ALL_EVENTS.map((e) => e.prize).filter((p): p is number => p !== null);
  return known.length ? known.reduce((a, b) => a + b, 0) : null;
}

/** Sum of confirmed per-event prizes for one track. */
export function prizeForCategory(category: string): number | null {
  const era = ERAS.find((e) => e.category === category);
  if (!era) return null;
  const known = era.events.map((e) => e.prize).filter((p): p is number => p !== null);
  return known.length ? known.reduce((a, b) => a + b, 0) : null;
}

/** The number the prize section actually renders. Null = section hidden. */
export function headlinePrizeTotal(): number | null {
  return PRIZE_POOL.total ?? prizeFromEvents();
}

